/// Repository path of the committed rolling `OpenAPI` document.
pub const OPENAPI_PATH: &str = "contracts/openapi/latest.json";

/// Generated document and the digest served in API response headers.
#[derive(Clone, Debug)]
pub struct OpenApiDocument {
    document: Value,
    digest: String,
}

impl OpenApiDocument {
    /// Returns the generated `OpenAPI` JSON value.
    #[must_use]
    pub const fn value(&self) -> &Value {
        &self.document
    }

    /// Returns the lowercase SHA-256 digest of the canonical generated bytes.
    #[must_use]
    pub fn digest(&self) -> &str {
        &self.digest
    }

    /// Serializes the document with deterministic indentation and a trailing newline.
    ///
    /// # Errors
    ///
    /// Returns an error if the JSON value cannot be serialized.
    pub fn to_pretty_bytes(&self) -> Result<Vec<u8>, serde_json::Error> {
        let mut bytes = serde_json::to_vec_pretty(&self.document)?;
        bytes.push(b'\n');
        Ok(bytes)
    }
}

/// Generates the rolling API contract entirely from Rust boundary schemas.
///
/// # Errors
///
/// Returns an error if the deterministic document cannot be serialized for hashing.
pub fn generate_openapi() -> Result<OpenApiDocument, serde_json::Error> {
    let document = json!({
        "openapi": "3.1.0",
        "info": {
            "title": "MeshSpan public API",
            "version": "latest",
            "license": {
                "name": "GNU General Public License v2.0 only",
                "identifier": "GPL-2.0-only"
            }
        },
        "servers": [{ "url": "/api/latest" }],
        "paths": paths(),
        "components": components()
    });
    let digest = format!("sha256:{}", hex_digest(&serde_json::to_vec(&document)?));
    Ok(OpenApiDocument { document, digest })
}

