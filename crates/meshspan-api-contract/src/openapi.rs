fn json_request(description: &str, schema_reference: &str) -> Value {
    json!({
        "description": description,
        "required": true,
        "content": {
            "application/json": {
                "schema": { "$ref": schema_reference }
            }
        }
    })
}

fn json_response(description: &str, schema_reference: &str) -> Value {
    json!({
        "description": description,
        "headers": response_headers(),
        "content": {
            "application/json": {
                "schema": { "$ref": schema_reference }
            }
        }
    })
}

fn session_response(description: &str) -> Value {
    let mut headers = response_headers();
    if let Some(headers) = headers.as_object_mut() {
        headers.insert(
            "Set-Cookie".to_owned(),
            json!({
                "required": true,
                "schema": { "type": "string", "minLength": 1 },
                "x-meshspan-sensitive": true
            }),
        );
        headers.insert(
            "MeshSpan-CSRF-Token".to_owned(),
            json!({
                "required": true,
                "schema": {
                    "type": "string",
                    "pattern": "^meshspan-csrf-v1\\.[0-9a-f]{32}\\.[0-9a-f]{64}$"
                },
                "x-meshspan-sensitive": true
            }),
        );
    }
    json!({
        "description": description,
        "headers": headers,
        "content": {
            "application/json": {
                "schema": { "$ref": "#/components/schemas/CreateSessionResponse" }
            }
        }
    })
}

fn response_headers() -> Value {
    json!({
        "MeshSpan-API-Version": {
            "required": true,
            "schema": { "type": "string", "const": "latest" }
        },
        "MeshSpan-API-Schema": {
            "required": true,
            "schema": {
                "type": "string",
                "pattern": "^sha256:[0-9a-f]{64}$"
            }
        }
    })
}

fn request_component<T: schemars::JsonSchema>() -> Value {
    schema_value(schema::request_schema::<T>())
}

fn response_component<T: schemars::JsonSchema>() -> Value {
    schema_value(schema::response_schema::<T>())
}

fn schema_value(schema: schemars::Schema) -> Value {
    schema.to_value()
}

fn hex_digest(bytes: &[u8]) -> String {
    const HEX: &[u8; 16] = b"0123456789abcdef";
    let digest = Sha256::digest(bytes);
    let mut output = String::with_capacity(digest.len() * 2);
    for byte in digest {
        output.push(char::from(HEX[usize::from(byte >> 4)]));
        output.push(char::from(HEX[usize::from(byte & 0x0f)]));
    }
    output
}
